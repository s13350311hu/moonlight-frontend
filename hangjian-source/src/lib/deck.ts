export interface WordCard {
  id: number
  /** [正位, 逆位] */
  faces: [string, string]
  facesJa: [string, string]
}

export const DECK: WordCard[] = FACES.map((faces, i) => ({
  id: i + 1,
  faces,
  facesJa: FACES_JA[i],
}))

/** 照目前的介面語言取出那一面的詞。 */
export function cardWords(card: WordCard, face: 0 | 1): string {
  return getLang() === 'ja' ? card.facesJa[face] : card.faces[face]
}
